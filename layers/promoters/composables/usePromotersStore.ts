/** Spreadsheet formats supported by the promoter export endpoint. */
export type PromoterExportFormat = "xlsx" | "csv";

/** Audience status filter supported by the audiences endpoint. */
export type PromoterAudienceStatusFilter =
  | "all"
  | "verified"
  | "unverified"
  | "transacted"
  | "not_transacted";

/** Promoter record (PromoterResource) returned by the list, create and update endpoints. */
export interface IPromoter extends ITableBodyData {
  id: string;
  campaignId: string;
  campaignName: string | null;
  name: string;
  email: string;
  phone: string | null;
  referralCode: string;
  appReferralLink: string | null;
  webReferralLink: string | null;
  avatarUrl: string | null;
  createdAt?: string;
  updatedAt?: string;
}

/** Promoter totals returned with the promoters list. */
export interface IPromoterSummary {
  totalPromoters: number;
  totalAudience: number;
  verifiedUsers: number;
  completedTrades: number;
  /** Percentage, e.g. `48.8`. */
  conversionRate: number;
}

/** Response data of `GET /admin/promoters`. */
export interface IPromoterListResponse {
  summary: IPromoterSummary;
  promoters: IPromoter[];
}

/** A referral code record attached to a promoter profile. */
export interface IPromoterReferralCode {
  id: string;
  code: string;
  label: string | null;
  deepLink: string | null;
  createdAt?: string;
}

/** Transaction totals on the promoter profile. */
export interface IPromoterTransactionMetrics {
  totalTransactions: number;
  successfulTransactions: number;
  thisWeekTransactions: number;
  easypayVolume: number;
  safewalletVolume: number;
  totalTradingVolume: number;
}

/** Audience counts on the promoter profile. */
export interface IPromoterAudienceMetrics {
  totalAudience: number;
  registeredAudience: number;
  verifiedAudience: number;
  unverifiedAudience: number;
  audienceWithTransaction: number;
}

/** USD volume and row count for one ledger slice. */
export interface IPromoterVolumeCount {
  volume: number;
  count: number;
}

/** Ledger breakdown behind the Transactions, Withdrawal and Utility tabs. */
export interface IPromoterBreakdown {
  transactions: IPromoterVolumeCount & {
    easypay: IPromoterVolumeCount;
    safewallet: IPromoterVolumeCount & {
      cash: IPromoterVolumeCount;
      crypto: IPromoterVolumeCount;
    };
  };
  deposits: IPromoterVolumeCount;
  withdrawals: IPromoterVolumeCount & {
    cash: IPromoterVolumeCount;
    crypto: IPromoterVolumeCount;
  };
  utility: IPromoterVolumeCount & {
    airtime: IPromoterVolumeCount;
    data: IPromoterVolumeCount;
  };
  lastTransactionAt: string | null;
}

/** Profile metrics. `transactions` and `breakdown` are `null` without `dashboard.basic.view`. */
export interface IPromoterMetrics {
  transactions: IPromoterTransactionMetrics | null;
  audience: IPromoterAudienceMetrics;
  breakdown: IPromoterBreakdown | null;
}

/** Response data of `GET /admin/promoters/{id}`. */
export interface IPromoterDetails extends IPromoter {
  referralCodes: IPromoterReferralCode[];
  metrics: IPromoterMetrics | null;
}

/** Filters applied to the promoter profile metrics. */
export interface IPromoterProfileFilters {
  timeframe: AnalyticsTimeframe;
  /** `YYYY-MM-DD`; only sent when `timeframe` is `custom`. */
  startDate?: string;
  /** `YYYY-MM-DD`; only sent when `timeframe` is `custom`. */
  endDate?: string;
  /** ISO alpha-2 country code; empty means all countries. */
  countryCode?: string;
}

/** Payload for onboarding a promoter. */
export interface ICreatePromoterPayload {
  campaignId: string;
  name: string;
  email: string;
  phone?: string;
  /** Auto-generated by the API when omitted. */
  referralCode?: string;
  avatarUrl?: string;
}

/** Payload for updating a promoter; every field is optional. */
export type IUpdatePromoterPayload = Partial<ICreatePromoterPayload>;

/** Payload for deleting several promoters at once. */
export interface IBatchDeletePromotersPayload {
  ids: string[];
}

/** Response data of the batch delete endpoint. */
export interface IBatchDeletePromotersResponse {
  deletedCount: number;
}

/** Audience member referred by a promoter (AudienceResource). */
export interface IPromoterAudience extends ITableBodyData {
  id: string;
  campaignId?: string;
  campaignName?: string | null;
  promoterId?: string | null;
  promoterName?: string | null;
  name: string;
  email: string;
  phone?: string | null;
  isVerified: boolean;
  hasTransacted: boolean;
  createdAt?: string;
}

/** Response data of `GET /admin/audiences?promoterId=`. */
export interface IPromoterAudienceListResponse {
  audiences: IPromoterAudience[];
}

/** Query parameters sent to the promoter profile endpoint. */
type PromoterProfileQuery = Record<string, string | undefined>;

/** Default profile filters, matching the "Last 30 days" selector. */
const defaultProfileFilters = (): IPromoterProfileFilters => ({
  timeframe: "last_30_days",
});

/** Turns profile filters into query parameters; dates are only sent for `custom`. */
const buildProfileQuery = (
  filters: IPromoterProfileFilters,
): PromoterProfileQuery => {
  const query: PromoterProfileQuery = { timeframe: filters.timeframe };

  if (filters.timeframe === "custom" && filters.startDate && filters.endDate) {
    query.startDate = filters.startDate;
    query.endDate = filters.endDate;
  }
  if (filters.countryCode) query.countryCode = filters.countryCode;

  return query;
};

/** Returns true when an API error is a 404 Not Found. */
const isNotFoundError = (error: unknown): boolean =>
  (error as { statusCode?: number })?.statusCode === 404;

/**
 * Reports an API error through the shared handler. The toast is skipped for
 * 401s because the session middleware already redirects to the login page.
 */
const handleApiError = (error: unknown, heading: string): void => {
  const isUnauthenticated =
    (error as { statusCode?: number })?.statusCode === 401;
  ApiErrorHandler(error, !isUnauthenticated, false, heading);
};

/** Provides promoter API state and actions. */
export const usePromotersStore = () => {
  const endpoints = {
    PROMOTERS: "/admin/promoters",
    PROMOTER: (id: string) => `/admin/promoters/${id}`,
    EXPORT: "/admin/promoters/export",
    BATCH_DELETE: "/admin/promoters/batch-delete",
    AUDIENCES: "/admin/audiences",
  };

  const state = {
    fetchingPromoters: useState<boolean>(
      "usePromotersStore.fetchingPromoters",
      () => false,
    ),
    fetchingPromoterDetails: useState<boolean>(
      "usePromotersStore.fetchingPromoterDetails",
      () => false,
    ),
    creatingPromoter: useState<boolean>(
      "usePromotersStore.creatingPromoter",
      () => false,
    ),
    updatingPromoter: useState<boolean>(
      "usePromotersStore.updatingPromoter",
      () => false,
    ),
    deletingPromoter: useState<boolean>(
      "usePromotersStore.deletingPromoter",
      () => false,
    ),
    batchDeletingPromoters: useState<boolean>(
      "usePromotersStore.batchDeletingPromoters",
      () => false,
    ),
    exportingPromoters: useState<boolean>(
      "usePromotersStore.exportingPromoters",
      () => false,
    ),
    fetchingPromoterAudiences: useState<boolean>(
      "usePromotersStore.fetchingPromoterAudiences",
      () => false,
    ),

    promoters: useState<IPromoter[]>("usePromotersStore.promoters", () => []),
    promoterSummary: useState<IPromoterSummary | null>(
      "usePromotersStore.promoterSummary",
      () => null,
    ),
    promotersPage: useState<number>("usePromotersStore.promotersPage", () => 1),
    promotersPerPage: useState<number>(
      "usePromotersStore.promotersPerPage",
      () => 10,
    ),
    promotersLastPage: useState<number>(
      "usePromotersStore.promotersLastPage",
      () => 1,
    ),
    promotersTotal: useState<number>(
      "usePromotersStore.promotersTotal",
      () => 0,
    ),
    promotersSearch: useState<string>(
      "usePromotersStore.promotersSearch",
      () => "",
    ),
    /** Empty string means all campaigns. */
    promotersCampaignId: useState<string>(
      "usePromotersStore.promotersCampaignId",
      () => "",
    ),

    selectedPromoter: useState<IPromoterDetails | null>(
      "usePromotersStore.selectedPromoter",
      () => null,
    ),
    profileFilters: useState<IPromoterProfileFilters>(
      "usePromotersStore.profileFilters",
      defaultProfileFilters,
    ),

    promoterAudiences: useState<IPromoterAudience[]>(
      "usePromotersStore.promoterAudiences",
      () => [],
    ),
    promoterAudiencesPage: useState<number>(
      "usePromotersStore.promoterAudiencesPage",
      () => 1,
    ),
    promoterAudiencesPerPage: useState<number>(
      "usePromotersStore.promoterAudiencesPerPage",
      () => 5,
    ),
    promoterAudiencesLastPage: useState<number>(
      "usePromotersStore.promoterAudiencesLastPage",
      () => 1,
    ),
    promoterAudiencesTotal: useState<number>(
      "usePromotersStore.promoterAudiencesTotal",
      () => 0,
    ),
    promoterAudiencesSearch: useState<string>(
      "usePromotersStore.promoterAudiencesSearch",
      () => "",
    ),
    promoterAudiencesStatus: useState<PromoterAudienceStatusFilter>(
      "usePromotersStore.promoterAudiencesStatus",
      () => "all",
    ),
  };

  const { can } = useAuthStore();

  const getters = {
    /** Promoter totals for the list summary cards, with zero fallbacks. */
    promoterStats: computed(() => ({
      totalPromoters: state.promoterSummary.value?.totalPromoters ?? 0,
      totalAudience: state.promoterSummary.value?.totalAudience ?? 0,
      verifiedUsers: state.promoterSummary.value?.verifiedUsers ?? 0,
      completedTrades: state.promoterSummary.value?.completedTrades ?? 0,
      conversionRate: state.promoterSummary.value?.conversionRate ?? 0,
    })),
    /** Whether the user may see the profile's transaction figures. */
    canViewPromoterTransactions: computed<boolean>(() =>
      can("dashboard.basic.view"),
    ),
  };

  /** Applies updated promoter fields to the selected promoter and the list. */
  const mergePromoter = (promoterId: string, changes: Partial<IPromoter>) => {
    if (state.selectedPromoter.value?.id === promoterId) {
      state.selectedPromoter.value = {
        ...state.selectedPromoter.value,
        ...changes,
      };
    }
    state.promoters.value = state.promoters.value.map((promoter) =>
      promoter.id === promoterId ? { ...promoter, ...changes } : promoter,
    );
  };

  const actions = {
    /**
     * Fetches one page of promoters using the stored search/campaign filters.
     * When a page beyond the first comes back empty or fails, the page state
     * rolls back to the last valid page.
     */
    async fetchPromoters(page: number = state.promotersPage.value) {
      const previousPage = state.promotersPage.value;
      state.promotersPage.value = page;
      state.fetchingPromoters.value = true;

      return useApiClientHandler()
        .$apiClient<IResponse<IPromoterListResponse, any, IPaginationMeta>>(
          endpoints.PROMOTERS,
          {
            method: "GET",
            query: {
              page,
              perPage: state.promotersPerPage.value,
              search: state.promotersSearch.value || undefined,
              campaignId: state.promotersCampaignId.value || undefined,
            },
          },
        )
        .then((response) => {
          const promoters = response.data?.promoters ?? [];
          state.promoterSummary.value = response.data?.summary ?? null;

          if (page > 1 && promoters.length === 0) {
            state.promotersPage.value = previousPage;
            return state.promoters.value;
          }

          state.promoters.value = promoters;
          state.promotersTotal.value = response.meta?.total ?? promoters.length;
          state.promotersLastPage.value = resolveLastPage(response.meta);
          state.promotersPage.value = response.meta?.currentPage ?? page;
          return promoters;
        })
        .catch((error) => {
          state.promotersPage.value = previousPage;
          handleApiError(error, "Promoter fetch failed");
          throw error;
        })
        .finally(() => {
          state.fetchingPromoters.value = false;
        });
    },

    /** Updates the search term and reloads the first page of promoters. */
    async setPromotersSearch(search: string) {
      state.promotersSearch.value = search.trim();
      return actions.fetchPromoters(1);
    },

    /** Updates the campaign filter (empty for all) and reloads the first page. */
    async setPromotersCampaign(campaignId: string) {
      state.promotersCampaignId.value = campaignId;
      return actions.fetchPromoters(1);
    },

    /**
     * Loads one promoter profile with metrics for the stored profile filters.
     * Resolves to `null` without a toast when the promoter does not exist.
     */
    async fetchPromoterDetails(promoterId: string) {
      state.fetchingPromoterDetails.value = true;

      return useApiClientHandler()
        .$apiClient<IResponse<IPromoterDetails>>(
          endpoints.PROMOTER(promoterId),
          {
            method: "GET",
            query: buildProfileQuery(state.profileFilters.value),
          },
        )
        .then((response) => {
          state.selectedPromoter.value = response.data ?? null;
          return state.selectedPromoter.value;
        })
        .catch((error) => {
          if (isNotFoundError(error)) {
            state.selectedPromoter.value = null;
            return null;
          }
          handleApiError(error, "Promoter profile fetch failed");
          throw error;
        })
        .finally(() => {
          state.fetchingPromoterDetails.value = false;
        });
    },

    /**
     * Merges new profile filters (dates are dropped unless the timeframe is
     * `custom`). Callers then refetch the profile.
     */
    setPromoterProfileFilters(partial: Partial<IPromoterProfileFilters>) {
      const next = { ...state.profileFilters.value, ...partial };
      if (next.timeframe !== "custom") {
        delete next.startDate;
        delete next.endDate;
      }
      if (!next.countryCode) delete next.countryCode;
      state.profileFilters.value = next;
      return next;
    },

    /** Onboards a promoter, then refreshes the first page of the list. */
    async createPromoter(payload: ICreatePromoterPayload) {
      state.creatingPromoter.value = true;

      return useApiClientHandler()
        .$apiClient<IResponse<IPromoter>>(endpoints.PROMOTERS, {
          method: "POST",
          body: payload,
        })
        .then((response) => {
          useToastHandler().triggerToast(
            `${payload.name} has been onboarded successfully.`,
            "success",
            "Promoter created",
            "large",
          );
          void actions.fetchPromoters(1).catch(() => undefined);
          return response.data;
        })
        .catch((error) => {
          handleApiError(error, "Promoter creation failed");
          throw error;
        })
        .finally(() => {
          state.creatingPromoter.value = false;
        });
    },

    /** Updates a promoter and merges the response into stored promoter state. */
    async updatePromoter(promoterId: string, payload: IUpdatePromoterPayload) {
      state.updatingPromoter.value = true;

      return useApiClientHandler()
        .$apiClient<IResponse<IPromoter>>(endpoints.PROMOTER(promoterId), {
          method: "PUT",
          body: payload,
        })
        .then((response) => {
          mergePromoter(promoterId, {
            ...(payload as Partial<IPromoter>),
            ...(response.data ?? {}),
          });
          useToastHandler().triggerToast(
            "The promoter profile has been saved.",
            "success",
            "Promoter updated",
            "large",
          );
          return response.data;
        })
        .catch((error) => {
          handleApiError(error, "Promoter update failed");
          throw error;
        })
        .finally(() => {
          state.updatingPromoter.value = false;
        });
    },

    /** Deletes (soft) a promoter and removes it from stored state. */
    async deletePromoter(promoterId: string) {
      state.deletingPromoter.value = true;

      return useApiClientHandler()
        .$apiClient<IResponse<null>>(endpoints.PROMOTER(promoterId), {
          method: "DELETE",
        })
        .then(() => {
          state.promoters.value = state.promoters.value.filter(
            (promoter) => promoter.id !== promoterId,
          );
          if (state.selectedPromoter.value?.id === promoterId) {
            state.selectedPromoter.value = null;
          }
          useToastHandler().triggerToast(
            "The promoter has been deleted.",
            "success",
            "Promoter deleted",
            "large",
          );
          return true;
        })
        .catch((error) => {
          handleApiError(error, "Promoter deletion failed");
          throw error;
        })
        .finally(() => {
          state.deletingPromoter.value = false;
        });
    },

    /**
     * Deletes several promoters, then reloads the current list page. Falls back
     * to the previous page when the current one no longer has promoters.
     */
    async batchDeletePromoters(promoterIds: string[]) {
      state.batchDeletingPromoters.value = true;
      const payload: IBatchDeletePromotersPayload = { ids: promoterIds };

      return useApiClientHandler()
        .$apiClient<IResponse<IBatchDeletePromotersResponse>>(
          endpoints.BATCH_DELETE,
          { method: "POST", body: payload },
        )
        .then((response) => {
          const deletedCount = response.data?.deletedCount ?? promoterIds.length;
          useToastHandler().triggerToast(
            `${deletedCount} promoter${deletedCount === 1 ? "" : "s"} deleted successfully.`,
            "success",
            "Promoters deleted",
            "large",
          );

          const remainingOnPage = state.promoters.value.filter(
            (promoter) => !promoterIds.includes(promoter.id),
          ).length;
          const targetPage =
            remainingOnPage === 0 && state.promotersPage.value > 1
              ? state.promotersPage.value - 1
              : state.promotersPage.value;
          void actions.fetchPromoters(targetPage).catch(() => undefined);
          return deletedCount;
        })
        .catch((error) => {
          handleApiError(error, "Promoter deletion failed");
          throw error;
        })
        .finally(() => {
          state.batchDeletingPromoters.value = false;
        });
    },

    /** Downloads the promoter list as a spreadsheet using the active filters. */
    async exportPromoters(format: PromoterExportFormat) {
      state.exportingPromoters.value = true;

      return useApiClientHandler()
        .$apiClient.raw<Blob>(endpoints.EXPORT, {
          method: "GET",
          responseType: "blob",
          query: {
            format,
            search: state.promotersSearch.value || undefined,
            campaignId: state.promotersCampaignId.value || undefined,
          },
        })
        .then((response) =>
          downloadResponseFile({
            responseData: response._data,
            contentType: response.headers.get("content-type"),
            contentDisposition: response.headers.get("content-disposition"),
            fallbackFileName: "promoters",
            fallbackExtension: format,
          }),
        )
        .catch((error) => {
          handleApiError(error, "Promoter export failed");
          throw error;
        })
        .finally(() => {
          state.exportingPromoters.value = false;
        });
    },

    /**
     * Fetches one page of audience members referred by a promoter, using the
     * stored search/status filters. Rolls the page back on an empty or failed
     * next page.
     */
    async fetchPromoterAudiences(
      promoterId: string,
      page: number = state.promoterAudiencesPage.value,
    ) {
      const previousPage = state.promoterAudiencesPage.value;
      state.promoterAudiencesPage.value = page;
      state.fetchingPromoterAudiences.value = true;

      return useApiClientHandler()
        .$apiClient<
          IResponse<IPromoterAudienceListResponse, any, IPaginationMeta>
        >(endpoints.AUDIENCES, {
          method: "GET",
          query: {
            page,
            perPage: state.promoterAudiencesPerPage.value,
            promoterId,
            search: state.promoterAudiencesSearch.value || undefined,
            status:
              state.promoterAudiencesStatus.value === "all"
                ? undefined
                : state.promoterAudiencesStatus.value,
          },
        })
        .then((response) => {
          const audiences = response.data?.audiences ?? [];
          if (page > 1 && audiences.length === 0) {
            state.promoterAudiencesPage.value = previousPage;
            return state.promoterAudiences.value;
          }

          state.promoterAudiences.value = audiences;
          state.promoterAudiencesTotal.value =
            response.meta?.total ?? audiences.length;
          state.promoterAudiencesLastPage.value = resolveLastPage(
            response.meta,
          );
          state.promoterAudiencesPage.value =
            response.meta?.currentPage ?? page;
          return audiences;
        })
        .catch((error) => {
          state.promoterAudiencesPage.value = previousPage;
          handleApiError(error, "Referred audience fetch failed");
          throw error;
        })
        .finally(() => {
          state.fetchingPromoterAudiences.value = false;
        });
    },

    /** Updates the referred-audience search term and reloads the first page. */
    async setPromoterAudiencesSearch(promoterId: string, search: string) {
      state.promoterAudiencesSearch.value = search.trim();
      return actions.fetchPromoterAudiences(promoterId, 1);
    },

    /** Updates the referred-audience status filter and reloads the first page. */
    async setPromoterAudiencesStatus(
      promoterId: string,
      status: PromoterAudienceStatusFilter,
    ) {
      state.promoterAudiencesStatus.value = status;
      return actions.fetchPromoterAudiences(promoterId, 1);
    },

    /** Clears the profile, its audience table and filters between promoters. */
    resetPromoterProfile() {
      state.selectedPromoter.value = null;
      state.profileFilters.value = defaultProfileFilters();
      state.promoterAudiences.value = [];
      state.promoterAudiencesPage.value = 1;
      state.promoterAudiencesLastPage.value = 1;
      state.promoterAudiencesTotal.value = 0;
      state.promoterAudiencesSearch.value = "";
      state.promoterAudiencesStatus.value = "all";
    },
  };

  return {
    ...state,
    ...getters,
    ...actions,
  };
};
